"""Build benchmarks/micro/REPORT.md from results_r.json and results_py.json (spec §9.1).

Usage: uv run python benchmarks/micro/report.py results_r.json results_py.json [REPORT.md]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def fmt(t: float) -> str:
    return f"{t * 1000:.1f} ms" if t < 1 else f"{t:.2f} s"


def main() -> None:
    r = json.loads(Path(sys.argv[1]).read_text())
    p = json.loads(Path(sys.argv[2]).read_text())
    out = Path(sys.argv[3] if len(sys.argv) > 3 else "benchmarks/micro/REPORT.md")
    rm, pm = r["meta"], p["meta"]
    stages = sorted({k.split("@")[0] for k in p if k != "meta"})
    lines = [
        "# Micro-benchmarks: pydada2 vs R dada2 (example data)",
        "",
        "Generated by `benchmarks/micro/report.py` from `run_r.R` and `run_py.py` (spec §9.1).",
        "Median wall time over repeated runs after one warm-up run; ratio = Python / R",
        "(< 1 means pydada2 is faster). The example data are tiny (2 x 1500 read pairs), so",
        "per-call overheads dominate; real speed-ups are measured on a larger dataset (phase 11).",
        "",
        f"* R: {rm['r_version']}, dada2 {rm['dada2']}, {rm['repeats']} repeats",
        f"* Python {pm['python']}, pydada2 {pm['pydada2']}, {pm['repeats']} repeats",
        f"* Machine: {p['meta']['cores']} logical CPUs",
        "",
        "| stage | threads | R | pydada2 | ratio |",
        "|---|---|---|---|---|",
    ]
    worst = []
    for st in stages:
        for nt in (1, 4):
            key = f"{st}@{nt}"
            if key not in p or key not in r:
                continue
            ratio = p[key] / r[key] if r[key] > 0 else float("nan")
            worst.append((ratio, key))
            lines.append(f"| {st} | {nt} | {fmt(r[key])} | {fmt(p[key])} | {ratio:.2f} |")
    over = [k for ratio, k in worst if ratio > 1.5]
    lines += [
        "",
        "Stages slower than 1.5x R: " + (", ".join(over) if over else "none") + ".",
        "",
    ]
    out.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
