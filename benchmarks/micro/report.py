"""Build benchmarks/micro/REPORT.md from results_r.json and results_py.json (spec §9.1).

Usage: uv run python benchmarks/micro/report.py results_r.json results_py.json [REPORT.md]
                                                [results_py_before.json]

With a fourth file (run_py.py run against an earlier pydada2), columns `before` and `speed-up`
(= before / now) compare the two pydada2 versions.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

CAVEATS = {
    "filter_and_trim": (
        "R's filterAndTrim parallelises over files only (2 files here), so it is timed at 1 and "
        "2 threads on both sides."
    ),
}


def fmt(t: float) -> str:
    if t < 1e-3:
        return f"{t * 1e6:.0f} µs"
    return f"{t * 1000:.1f} ms" if t < 1 else f"{t:.2f} s"


def gc_share(stage: str, r_time: float, rm: dict) -> tuple[str, str] | None:
    """(note, share) for stages whose R function calls gc() internally."""
    n_gc = (rm.get("internal_gc") or {}).get(stage)
    gc_s = rm.get("gc_seconds")
    if not n_gc or gc_s is None or r_time <= 0:
        return None
    note = (
        f"R's function calls gc() {n_gc:g}x per call (≈ {fmt(gc_s)} each in this R session; "
        "column `R gc`: share of R's time). The ratio mostly measures those collections, not "
        "the algorithm."
    )
    return note, f"{min(1.0, n_gc * gc_s / r_time):.0%}"


def main() -> None:
    r = json.loads(Path(sys.argv[1]).read_text())
    p = json.loads(Path(sys.argv[2]).read_text())
    out = Path(sys.argv[3] if len(sys.argv) > 3 else "benchmarks/micro/REPORT.md")
    b = json.loads(Path(sys.argv[4]).read_text()) if len(sys.argv) > 4 else None
    rm, pm = r["meta"], p["meta"]
    keys = sorted(k for k in p if k != "meta")
    lines = [
        "# Micro-benchmarks: pydada2 vs R dada2 (example data)",
        "",
        "Generated by `benchmarks/micro/report.py` from `run_r.R` and `run_py.py` (spec §9.1).",
        "Per-call wall time: median over repeated samples after one warm-up run; stages faster",
        f"than {pm.get('min_sample', 0.2)} s are timed in loops (column `loops`: calls per sample",
        "in R / Python), so timer resolution does not distort sub-millisecond stages. A full",
        "garbage collection runs before every sample, outside the timed region.",
        "Ratio = Python / R (< 1 means pydada2 is faster). The example data are tiny",
        "(2 x 1500 read pairs), so per-call overheads dominate; real speed-ups are measured on a",
        "larger dataset (benchmarks/dataset).",
        "",
        f"* R: {rm['r_version']}, dada2 {rm['dada2']}, {rm['repeats']} repeats",
        f"* Python {pm['python']}, pydada2 {pm['pydada2']} ({pm.get('commit', '?')}), "
        f"{pm['repeats']} repeats",
        *(
            [
                f"* Before: pydada2 {b['meta']['pydada2']} ({b['meta'].get('commit', '?')}), "
                f"{b['meta']['repeats']} repeats"
            ]
            if b
            else []
        ),
        f"* Machine: {pm['cores']} logical CPUs",
        f"* Chimera stages: example sequence table plus {pm.get('n_chimeras')} synthetic "
        "chimeras; assign_species: "
        f"{pm.get('n_species_queries')} reference windows, {pm.get('species_hits')} species hits",
        "",
    ]
    for what in ("n_chimeras", "n_species_queries", "species_hits"):
        if rm.get(what) != pm.get(what):
            lines += [f"**Warning: inputs differ between R and Python ({what}: "
                      f"{rm.get(what)} vs {pm.get(what)}).**", ""]  # fmt: skip
    extra_h = " before | speed-up |" if b else ""
    lines += [
        "| stage | threads | R | pydada2 | ratio | loops | R gc |" + extra_h,
        "|---|---|---|---|---|---|---|" + ("---|---|" if b else ""),
    ]

    def vs_before(key: str) -> str:
        if not b:
            return ""
        if key not in b:
            return " n/a | n/a |"
        return f" {fmt(b[key])} | {b[key] / p[key]:.1f}x |"

    ratios, only_py, notes = [], [], []
    rl, pl = rm.get("loops", {}), pm.get("loops", {})
    for key in keys:
        stage, nt = key.split("@")
        if key not in r:
            only_py.append(key)
            continue
        ratio = p[key] / r[key] if r[key] > 0 else float("nan")
        ratios.append((ratio, key))
        gc = gc_share(stage, r[key], rm)
        for note in (CAVEATS.get(stage), gc[0] if gc else None):
            if note and all((s, n) != (stage, note) for s, n, _ in notes):
                notes.append((stage, note, len(notes) + 1))
        idx = [i for s, _, i in notes if s == stage]
        mark = (" " + ",".join(f"[{i}]" for i in idx)) if idx else ""
        loops = f"{rl.get(key, '?')} / {pl.get(key, '?')}"
        lines.append(
            f"| {stage}{mark} | {nt} | {fmt(r[key])} | {fmt(p[key])} | {ratio:.2f} | {loops} "
            f"| {gc[1] if gc else ''} |{vs_before(key)}"
        )
    if notes:
        lines += [""] + [f"[{i}] `{s}`: {n}" for s, n, i in notes]
    if only_py:
        lines += [
            "",
            "pydada2 multithreaded, where R has no multithreaded implementation (compare with the",
            "single-threaded R row above):",
            "",
            "| stage | threads | pydada2 | R (1 thread) | ratio |" + extra_h,
            "|---|---|---|---|---|" + ("---|---|" if b else ""),
        ]
        for key in only_py:
            stage, nt = key.split("@")
            r1 = r.get(f"{stage}@1")
            ratio = f"{p[key] / r1:.2f}" if r1 else "n/a"
            lines.append(
                f"| {stage} | {nt} | {fmt(p[key])} | {fmt(r1) if r1 else 'n/a'} | {ratio} |"
                + vs_before(key)
            )
    over = [k for ratio, k in ratios if ratio > 1.5]
    lines += [
        "",
        "Stages slower than 1.5x R: " + (", ".join(over) if over else "none") + ".",
        "",
    ]
    out.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
